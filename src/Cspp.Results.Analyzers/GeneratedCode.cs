using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Cspp.Results.Analyzers;

/// <summary>
/// Recognizes generated code the way the compiler does, for syntax trees other than the one being analyzed.
/// </summary>
internal static class GeneratedCode
{
    private const string GeneratedCodeOption = "generated_code";

    private static readonly string[] GeneratedFileSuffixes = [".designer.cs", ".generated.cs", ".g.cs", ".g.i.cs"];

    private static readonly string[] GeneratedComments = ["<auto-generated", "<autogenerated"];

    /// <summary>
    /// Determines whether <paramref name="tree" /> is generated code: <c>generated_code</c> set in an
    /// <c>.editorconfig</c>, a generated file name such as <c>*.g.cs</c>, or an <c>&lt;auto-generated&gt;</c> comment
    /// at the top of the file.
    /// </summary>
    /// <param name="tree">The syntax tree to check.</param>
    /// <param name="options">The analyzer options, which hold the <c>.editorconfig</c> settings.</param>
    /// <param name="cancellationToken">A token to cancel the check.</param>
    /// <returns><see langword="true" /> if <paramref name="tree" /> is generated code.</returns>
    public static bool IsGenerated(SyntaxTree tree, AnalyzerOptions options, CancellationToken cancellationToken)
    {
        // An .editorconfig setting overrides the file name and the comment either way.
        if (options.AnalyzerConfigOptionsProvider.GetOptions(tree).TryGetValue(GeneratedCodeOption, out string? setting))
        {
            return string.Equals(setting, "true", StringComparison.OrdinalIgnoreCase);
        }

        string fileName = Path.GetFileName(tree.FilePath);
        if (fileName.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase)
            || GeneratedFileSuffixes.Any(suffix => fileName.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)))
        {
            return true;
        }

        return tree.GetRoot(cancellationToken).GetLeadingTrivia()
            .Where(trivia => trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
            .Any(comment => GeneratedComments.Any(marker =>
                comment.ToString().IndexOf(marker, StringComparison.OrdinalIgnoreCase) >= 0));
    }
}